#!/usr/bin/env python3
"""Regenerate rust-migration/API-LEDGER.md: every Laravel /api route (from `php artisan route:list --json`)
and whether the Rust gateway serves it natively (parsed from rust-backend/src/api/mod.rs `.route(...)`).

    php artisan route:list --path=api --json > /tmp/routes.json
    python3 -I scripts/parity/ledger.py /tmp/routes.json

Native routes may still delegate individual requests to Laravel (marked `ponytail:` in the code).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MOD_RS = ROOT / "rust-backend" / "src" / "api" / "mod.rs"
OUT = ROOT / "rust-migration" / "API-LEDGER.md"
METHODS = ("get", "post", "patch", "put", "delete")


def rust_routes() -> set[tuple[str, str]]:
    """(METHOD, laravel-style path) pairs registered in api::router()."""
    src = MOD_RS.read_text()
    pairs: set[tuple[str, str]] = set()
    # Each `.route("path", handlers)` call; handlers end at the matching close paren of `.route(`.
    for m in re.finditer(r'\.route\(\s*"([^"]+)"\s*,', src):
        depth, i = 1, m.end()
        while i < len(src) and depth:
            depth += {"(": 1, ")": -1}.get(src[i], 0)
            i += 1
        handlers = src[m.end() : i - 1]
        laravel_path = re.sub(r":(\w+)", r"{\1}", m.group(1)).lstrip("/")
        for method in METHODS:
            if re.search(rf"(?<![\w]){method}\(", handlers):
                pairs.add((method.upper(), laravel_path))
    return pairs


def normalize(path: str) -> str:
    """Compare paths ignoring parameter names: {uuid} == {id}."""
    return re.sub(r"\{[^}]+\}", "{}", path)


def main() -> int:
    routes = json.loads(Path(sys.argv[1]).read_text())
    native = {(m, normalize(p)) for m, p in rust_routes()}
    rows = []
    for r in routes:
        uri = r["uri"]
        if not uri.startswith("api/"):
            continue
        action = (r.get("action") or "").split("\\")[-1]
        ability = next((x.split(":", 1)[1] for x in r.get("middleware", []) if x.startswith("api.ability:")), "")
        for method in r["method"].split("|"):
            if method == "HEAD":
                continue
            rows.append((uri, method, action, ability, (method, normalize(uri)) in native))
    rows.sort()
    done = sum(1 for row in rows if row[4])
    lines = [
        "# API ledger: Laravel `/api` routes vs Rust",
        "",
        "Generated by `scripts/parity/ledger.py` from `php artisan route:list --path=api --json` and the routes",
        "registered in `rust-backend/src/api/mod.rs`. \"native\" routes are served by Rust (with every role checked",
        "by `scripts/parity/compare.py`); some still forward specific requests to Laravel, marked `ponytail:` in",
        "the code. \"proxied\" routes are answered by Laravel.",
        "",
        f"**{done} of {len(rows)} route+method pairs native.**",
        "",
        "| Method | Path | Laravel action | Ability | Rust |",
        "| --- | --- | --- | --- | --- |",
    ]
    for uri, method, action, ability, is_native in rows:
        lines.append(f"| {method} | `/{uri}` | `{action}` | {ability or '—'} | {'native' if is_native else 'proxied'} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{done}/{len(rows)} native")
    return 0


if __name__ == "__main__":
    sys.exit(main())
